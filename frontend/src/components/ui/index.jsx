export function Modal({ open, onClose, title, children, footer, width }) {
  const ref = useRef(null);
  useEffect(() => {
    if (!open) return undefined;
    const prev = document.activeElement;
    const onKey = (e) => { if (e.key === 'Escape') onClose?.(); };
    window.addEventListener('keydown', onKey);
    setTimeout(() => ref.current?.querySelector('button, input, select, textarea, [tabindex]')?.focus(), 30);
    return () => { window.removeEventListener('keydown', onKey); prev?.focus?.(); };
  }, [open, onClose]);
  return (
    <AnimatePresence>
      {open && (
        <motion.div className="modal-backdrop" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}
          onMouseDown={(e) => { if (e.target === e.currentTarget) onClose?.(); }}>
          <motion.div ref={ref} className="modal" role="dialog" aria-modal="true" aria-label={typeof title === 'string' ? title : undefined}
            style={width ? { width: `min(${width}px, 100%)` } : undefined}
            initial={{ opacity: 0, y: 8, scale: 0.98 }} animate={{ opacity: 1, y: 0, scale: 1 }} exit={{ opacity: 0, y: 6, scale: 0.98 }}
            transition={{ duration: 0.18, ease: [0.22, 1, 0.36, 1] }}>
            <div className="modal-head row-between">
              <h2>{title}</h2>
              <button className="btn btn-ghost btn-sm btn-icon" onClick={onClose} aria-label="Close dialog"><X size={15} /></button>
            </div>
            <div className="modal-body">{children}</div>
            {footer && <div className="modal-foot">{footer}</div>}
          </motion.div>
        </motion.div>
      )}
    </AnimatePresence>
  );
}

export function ConfirmDialog({ open, onClose, onConfirm, title, children, confirmLabel = 'Delete', danger = true, loading }) {
  return (
    <Modal open={open} onClose={onClose} title={title}
      footer={<><Button onClick={onClose}>Cancel</Button><Button variant={danger ? 'danger' : 'primary'} onClick={onConfirm} loading={loading}>{confirmLabel}</Button></>}>
      {children}
    </Modal>
  );
}

const STATUS = {
  completed: ['good', 'Completed'],
  running: ['info', 'Running'],
  queued: ['default', 'Queued'],
  failed: ['bad', 'Failed'],
  cancelled: ['default', 'Cancelled'],
  initializing: ['default', 'Queued'],
  training: ['info', 'Running'],
};

export function StatusBadge({ status }) {
  const [tone, label] = STATUS[status] || ['default', status];
  const active = status === 'running' || status === 'queued' || status === 'training';
  return (
    <Badge tone={tone === 'default' ? undefined : tone}>
      <span className={`dot ${active ? 'dot-pulse' : ''}`} />
      {label}
    </Badge>
  );
}

